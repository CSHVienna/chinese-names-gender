INPUT_FILE = 'aps_pinyin_given_names.csv'
OUTPUT_FILE = 'aps_pinyin_given_names_gendered.csv'

rows = []
with open(INPUT_FILE, newline='') as f:
    reader = csv.reader(f)
    header = next(reader)
    for row in reader:
        name = row[1].strip() if len(row) >= 2 else ''
        gender = GENDER_MAP.get(name.lower(), 'unknown')
        rows.append(row + [gender])

with open(OUTPUT_FILE, 'w', newline='') as f:
    writer = csv.writer(f)
    writer.writerow(header + ['py_gender_claude'])
    writer.writerows(rows)

# Print summary
