def token_score(name: str, token: str, weight: float) -> float:
    if name == token:
        return weight * 0.9
    score = 0.0
    if name.endswith(token):
        score += weight
    if name.startswith(token):
        score += weight * 0.7
    elif token in name:
        score += weight * 0.45
    return score


def infer_gender(name: str) -> str:
    if pd.isna(name):
        return "unknown"
    normalized = str(name).strip().lower()
    if not normalized:
        return "unknown"
    if normalized in EXACT_LABELS:
        return EXACT_LABELS[normalized]
    if not normalized.isalpha():
        return "unknown"
    if len(normalized) <= 4:
        if normalized in NEUTRAL_SINGLES:
            return "neutral"
        if normalized in MALE_TOKENS and MALE_TOKENS[normalized] >= 1.5:
            return "male"
        if normalized in FEMALE_TOKENS and FEMALE_TOKENS[normalized] >= 1.5:
            return "female"
        return "unknown"

    male_score = sum(token_score(normalized, token, weight) for token, weight in MALE_TOKENS.items())
    female_score = sum(token_score(normalized, token, weight) for token, weight in FEMALE_TOKENS.items())

    if normalized.count(normalized[: len(normalized) // 2]) == 2 and len(normalized) % 2 == 0:
        if female_score > male_score:
            return "female"
        return "neutral"

    if male_score >= 1.6 and male_score >= female_score + 1.0:
        return "male"
    if female_score >= 1.6 and female_score >= male_score + 1.0:
        return "female"
    if male_score >= 0.8 or female_score >= 0.8:
        return "neutral"
    return "unknown"


def main() -> None:
    df = pd.read_csv(SOURCE_PATH, index_col=0)
    df["py_gender_gpt"] = df["py_givenname"].map(infer_gender)
    df.to_csv(OUTPUT_PATH)

    counts = df["py_gender_gpt"].value_counts().sort_index()
    print(f"Wrote {len(df)} rows to {OUTPUT_PATH}")
    print(counts.to_string())


if __name__ == "__main__":
    main()